#!/usr/bin/env python3
"""
PERT / CPM progress tracker.

Reads docs/plan/tasks.toml and writes docs/plan/PROGRESS.md with:
  - overall progress, remaining effort (PERT expected value ± σ), next task
  - progress per batch
  - dependency network (Mermaid flowchart, coloured by status, critical path marked)
  - single-agent timeline (Mermaid Gantt, in execution order)
  - CPM table: expected duration, earliest/latest start/finish, slack

Usage:
  python3 docs/plan/tools/pert.py           # regenerate PROGRESS.md
  python3 docs/plan/tools/pert.py --check   # exit 1 if PROGRESS.md is out of date (used by CI)

PERT: te = (o + 4m + p) / 6, σ = (p - o) / 6. Durations are agent-hours of work, not calendar time.
CPM assumes unlimited parallelism; the timeline assumes one agent working through the batches in order.
"""
import math
import sys
import tomllib
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tasks.toml"
OUT = ROOT / "PROGRESS.md"
TIMELINE_START = datetime(2026, 11, 12, 9, 0)   # fixed anchor so the output is reproducible

ICON = {"done": "✅", "in-progress": "🔄", "todo": "⬜", "on-hold": "⏸️"}


def load():
    data = tomllib.loads(SRC.read_text(encoding="utf-8"))
    sizes, phases = data["sizes"], data["phases"]
    tasks = {}
    for t in data["tasks"]:
        o, m, p = t.get("est") or sizes[t["size"]]
        t["te"] = (o + 4 * m + p) / 6
        t["var"] = ((p - o) / 6) ** 2
        tasks[t["id"]] = t
    for t in tasks.values():
        for d in t["deps"]:
            if d not in tasks:
                sys.exit(f"tasks.toml: {t['id']} depends on unknown task {d}")
    return tasks, phases


def topo(tasks):
    order, seen, stack = [], set(), set()

    def visit(i):
        if i in seen:
            return
        if i in stack:
            sys.exit(f"tasks.toml: dependency cycle at {i}")
        stack.add(i)
        for d in tasks[i]["deps"]:
            visit(d)
        stack.discard(i)
        seen.add(i)
        order.append(i)

    for i in tasks:
        visit(i)
    return order


def cpm(tasks, remaining_only):
    """Forward/backward pass. remaining_only: finished tasks count as 0 h."""
    order = topo(tasks)
    dur = {i: (0.0 if remaining_only and tasks[i]["status"] == "done" else tasks[i]["te"]) for i in tasks}
    es, ef = {}, {}
    for i in order:
        es[i] = max((ef[d] for d in tasks[i]["deps"]), default=0.0)
        ef[i] = es[i] + dur[i]
    end = max(ef.values(), default=0.0)
    succ = {i: [] for i in tasks}
    for i in tasks:
        for d in tasks[i]["deps"]:
            succ[d].append(i)
    lf, ls = {}, {}
    for i in reversed(order):
        lf[i] = min((ls[s] for s in succ[i]), default=end)
        ls[i] = lf[i] - dur[i]
    slack = {i: ls[i] - es[i] for i in tasks}
    # critical path: walk from a zero-slack start through zero-slack successors
    crit = {i for i in tasks if abs(slack[i]) < 1e-9 and dur[i] > 0}
    path, cur = [], None
    starts = sorted((i for i in crit if not any(d in crit for d in tasks[i]["deps"])), key=lambda i: es[i])
    cur = starts[0] if starts else None
    while cur:
        path.append(cur)
        nxt = [s for s in succ[cur] if s in crit and abs(es[s] - ef[cur]) < 1e-9]
        cur = sorted(nxt)[0] if nxt else None
    var = sum(tasks[i]["var"] for i in path)
    return dict(es=es, ef=ef, ls=ls, lf=lf, slack=slack, end=end, path=path, sigma=math.sqrt(var), dur=dur)


def bar(frac, width=30):
    n = round(frac * width)
    return "█" * n + "░" * (width - n)


def fmt(h):
    return f"{h:.1f}"


def render(tasks, phases):
    ids_exec = sorted(tasks, key=lambda i: (tasks[i]["batch"] or 99, list(tasks).index(i)))
    active = [i for i in tasks if tasks[i]["status"] != "on-hold"]
    done = [i for i in active if tasks[i]["status"] == "done"]
    total_te = sum(tasks[i]["te"] for i in active)
    done_te = sum(tasks[i]["te"] for i in done)
    rem = [i for i in active if tasks[i]["status"] != "done"]
    rem_te = sum(tasks[i]["te"] for i in rem)
    rem_sigma = math.sqrt(sum(tasks[i]["var"] for i in rem))
    full, left = cpm(tasks, False), cpm(tasks, True)
    nxt = next((i for i in ids_exec if tasks[i]["status"] == "todo"
                and all(tasks[d]["status"] == "done" for d in tasks[i]["deps"])), None)
    in_prog = [i for i in tasks if tasks[i]["status"] == "in-progress"]
    on_hold = [i for i in tasks if tasks[i]["status"] == "on-hold"]
    crit_left = [i for i in left["path"]]

    L = []
    L += ["# Development progress (PERT / CPM)", "",
          "> Generated by `python3 docs/plan/tools/pert.py` from [`tasks.toml`](tasks.toml) — do not edit by hand.",
          "> Task descriptions: [BACKLOG.md](BACKLOG.md) · Hand-off notes: [HANDOFF.md](HANDOFF.md).", ""]
    L += ["## Summary", "",
          f"| | |", "|---|---|",
          f"| Tasks done | **{len(done)} / {len(active)}** `{bar(len(done) / len(active))}` {100 * len(done) / len(active):.0f}% |",
          f"| Effort done (PERT) | **{fmt(done_te)} / {fmt(total_te)} h** `{bar(done_te / total_te)}` {100 * done_te / total_te:.0f}% |",
          f"| Remaining effort, one agent in sequence | **{fmt(rem_te)} h ± {fmt(rem_sigma)}** of agent working time (calendar time depends on plan usage limits and your reviews) |",
          f"| Remaining critical path (if work could run in parallel) | {fmt(left['end'])} h ± {fmt(left['sigma'])} |",
          f"| In progress | {', '.join(in_prog) or '—'} |",
          f"| Next task | **{nxt or '—'}**{' — ' + tasks[nxt]['title'] if nxt else ''} |",
          f"| On hold | {', '.join(f'{i} ({tasks[i]['title']})' for i in on_hold) or '—'} |",
          "",
          f"**Critical path (remaining):** {' → '.join(crit_left) or '—'}", ""]

    L += ["## Batches", "", "| Batch | Tasks | Done | Progress |", "|---|---|---|---|"]
    for b in sorted({tasks[i]["batch"] for i in active}):
        ids = [i for i in ids_exec if tasks[i]["batch"] == b and tasks[i]["status"] != "on-hold"]
        d = sum(tasks[i]["status"] == "done" for i in ids)
        cells = " ".join(f"{ICON[tasks[i]['status']]}{i}" for i in ids)
        L.append(f"| {b} | {cells} | {d}/{len(ids)} | `{bar(d / len(ids), 10)}` |")
    L.append("")

    # ---- dependency network
    L += ["## Dependency network", "",
          "Green = done · blue = in progress · white = to do · grey = on hold · **red border = remaining critical path**.", "",
          "```mermaid", "flowchart LR"]
    for ph, name in phases.items():
        ids = [i for i in tasks if tasks[i]["phase"] == ph]
        if not ids:
            continue
        L.append(f'  subgraph {ph}["{name}"]')
        for i in ids:
            title = tasks[i]["title"].replace('"', "'")
            L.append(f'    {i}["{i}<br/>{title}"]')
        L.append("  end")
    for i in tasks:
        for d in tasks[i]["deps"]:
            L.append(f"  {d} --> {i}")
    L += ["  classDef done fill:#d4edda,stroke:#28a745,color:#155724",
          "  classDef inprogress fill:#cce5ff,stroke:#004085,color:#004085",
          "  classDef todo fill:#ffffff,stroke:#6c757d,color:#212529",
          "  classDef onhold fill:#e2e3e5,stroke:#6c757d,color:#6c757d,stroke-dasharray: 4 3",
          "  classDef critical stroke:#dc3545,stroke-width:3px"]
    for st, cls in [("done", "done"), ("in-progress", "inprogress"), ("todo", "todo"), ("on-hold", "onhold")]:
        ids = [i for i in tasks if tasks[i]["status"] == st]
        if ids:
            L.append(f"  class {','.join(ids)} {cls}")
    if crit_left:
        L.append(f"  class {','.join(crit_left)} critical")
    L += ["```", ""]

    # ---- timeline
    L += ["## Timeline (one agent, execution order)", "",
          "Bars are PERT expected **agent working hours** laid end to end in batch order — not calendar dates.", "",
          "```mermaid", "gantt", "  dateFormat YYYY-MM-DD HH:mm", "  axisFormat %d/%m %H:%M", "  todayMarker off"]
    t = TIMELINE_START
    for b in sorted({tasks[i]["batch"] for i in active}):
        L.append(f"  section Batch {b}")
        for i in [x for x in ids_exec if tasks[x]["batch"] == b and tasks[x]["status"] != "on-hold"]:
            st = tasks[i]["status"]
            tag = {"done": "done, ", "in-progress": "active, "}.get(st, "crit, " if i in crit_left else "")
            mins = max(15, round(tasks[i]["te"] * 60))
            L.append(f"  {i} {tasks[i]['title'].replace(':', ' ')} :{tag}{i.lower()}, {t:%Y-%m-%d %H:%M}, {mins}m")
            t += timedelta(minutes=mins)
    L += ["```", ""]

    # ---- CPM table
    L += ["## CPM table (all tasks, unlimited parallelism)", "",
          "te = expected hours; ES/EF = earliest start/finish; LS/LF = latest start/finish; slack = LS − ES (hours).", "",
          "| | ID | Task | Deps | te | σ | ES | EF | LS | LF | Slack | PR |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i in ids_exec:
        x = tasks[i]
        crit = " 🔴" if i in full["path"] else ""
        pr = f"#{x['pr']}" if x.get("pr") else ""
        L.append(f"| {ICON[x['status']]} | **{i}**{crit} | {x['title']} | {', '.join(x['deps']) or '—'} | {fmt(x['te'])} | "
                 f"{fmt(math.sqrt(x['var']))} | {fmt(full['es'][i])} | {fmt(full['ef'][i])} | {fmt(full['ls'][i])} | "
                 f"{fmt(full['lf'][i])} | {fmt(full['slack'][i])} | {pr} |")
    L += ["", f"Whole-project critical path 🔴: {' → '.join(full['path'])} = {fmt(full['end'])} h ± {fmt(full['sigma'])}", ""]
    return "\n".join(L)


def main():
    tasks, phases = load()
    text = render(tasks, phases)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/plan/PROGRESS.md is out of date: run  python3 docs/plan/tools/pert.py")
            sys.exit(1)
        print("PROGRESS.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT.parents[1])}")


if __name__ == "__main__":
    main()
